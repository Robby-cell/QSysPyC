use qsys_ir::*;
use qsys_model::{
    ControlKind, ControlLayoutDef, ControlStyle, GraphicItem, GraphicItemKind, PageLayout,
    PropertyKind, is_design_time_method,
};

use crate::context::CodegenContext;
use crate::emitter::{LuaEmitter, escape_lua_string, format_count_lua_expr, format_lua_float};

pub fn emit_plugin(plugin: &IRPlugin, ctx: &mut CodegenContext) -> String {
    // Register controls and properties
    for ctl in &plugin.controls {
        ctx.controls.insert(ctl.id, ctl.def.clone());
    }
    for prop in &plugin.properties {
        ctx.properties.insert(prop.id, prop.def.clone());
    }
    for binding in &plugin.event_bindings {
        ctx.method_handler_controls
            .insert(binding.handler_name.clone(), binding.control_id);
    }

    // Pre-load symbol names
    ctx.symbol_names.extend(plugin.symbol_names.clone());

    // Register method names
    for method in &plugin.methods {
        let fn_name = format!("{}_{}", plugin.class_name, method.name);
        ctx.functions.insert(method.id, fn_name);
    }

    let mut emitter = LuaEmitter::new(ctx);

    emitter.write_line("-- Generated by QSysPy Compiler (Lua 5.3)");
    emitter.write_line("-- Target: Q-SYS Designer Plugin\n");

    // Emit the truthy helper at top-level so both design-time and runtime can use it
    emit_truthy_helper(&mut emitter);

    // Emit top-level statements and helper classes in declaration order
    emitter.emit_statements(&plugin.top_level_stmts);

    // Emit PluginInfo
    emit_plugin_info(&mut emitter, &plugin.info);

    if let Some(m) = plugin.methods.iter().find(|m| m.name == "get_properties") {
        emit_lifecycle_method(&mut emitter, "GetProperties", m);
    } else {
        emit_get_properties(&mut emitter, &plugin.properties);
    }

    // Emit other design-time lifecycle hooks
    if let Some(m) = plugin
        .methods
        .iter()
        .find(|m| m.name == "rectify_properties")
    {
        emit_lifecycle_method(&mut emitter, "RectifyProperties", m);
    }

    if let Some(m) = plugin.methods.iter().find(|m| m.name == "get_color") {
        emit_lifecycle_method(&mut emitter, "GetColor", m);
    }

    if let Some(m) = plugin.methods.iter().find(|m| m.name == "get_pretty_name") {
        emit_lifecycle_method(&mut emitter, "GetPrettyName", m);
    }

    if let Some(m) = plugin.methods.iter().find(|m| m.name == "get_pages") {
        emit_lifecycle_method(&mut emitter, "GetPages", m);
    } else if !plugin.pages.is_empty() {
        emit_get_pages(&mut emitter, &plugin.pages);
    }

    if let Some(m) = plugin.methods.iter().find(|m| m.name == "get_controls") {
        emit_lifecycle_method(&mut emitter, "GetControls", m);
    } else {
        emit_get_controls(&mut emitter, &plugin.controls);
    }

    if let Some(m) = plugin
        .methods
        .iter()
        .find(|m| m.name == "get_control_layout")
    {
        emit_lifecycle_method(&mut emitter, "GetControlLayout", m);
    } else {
        emit_get_control_layout(&mut emitter, &plugin.pages);
    }

    if let Some(m) = plugin.methods.iter().find(|m| m.name == "get_components") {
        emit_lifecycle_method(&mut emitter, "GetComponents", m);
    }

    if let Some(m) = plugin.methods.iter().find(|m| m.name == "get_pins") {
        emit_lifecycle_method(&mut emitter, "GetPins", m);
    }

    if let Some(m) = plugin.methods.iter().find(|m| m.name == "get_wiring") {
        emit_lifecycle_method(&mut emitter, "GetWiring", m);
    }

    // Runtime Phase (guarded by `if Controls then`)
    emitter.write_line("if Controls then");
    emitter.indent();
    let runtime_body_offset = emitter.buffer.len();

    // Emit runtime methods (excluding design-time lifecycle methods)
    for method in &plugin.methods {
        if is_design_time_method(&method.name) {
            continue;
        }
        emit_method(&mut emitter, &plugin.class_name, method);
    }

    // Emit event bindings
    for binding in &plugin.event_bindings {
        let ctl_ref = format!(
            "Controls[{}]",
            crate::emitter::escape_lua_string(&binding.control_name)
        );
        let handler_fn = format!("{}_{}", plugin.class_name, binding.handler_name);
        let ctl_def = plugin
            .controls
            .iter()
            .find(|c| c.id == binding.control_id)
            .map(|c| &c.def);
        let ctl_count = ctl_def.map(|d| d.count).unwrap_or(1);
        let ctl_count_prop = ctl_def.and_then(|d| d.count_property.as_deref());

        if let Some(prop_name) = ctl_count_prop {
            let prop_ref = format_count_lua_expr(prop_name, "Properties");
            if let Some(ch_idx) = binding.channel_index {
                if ch_idx == 0 {
                    emitter.write_line(&format!("if {prop_ref} == 1 then"));
                    emitter.indent();
                    emitter.write_line(&format!("{ctl_ref}.EventHandler = function(ctl)"));
                    emitter.indent();
                    emitter.write_line(&format!("{handler_fn}(nil, ctl)"));
                    emitter.dedent();
                    emitter.write_line("end");
                    emitter.dedent();
                    emitter.write_line(&format!("elseif {prop_ref} >= 1 then"));
                    emitter.indent();
                    emitter.write_line(&format!("{ctl_ref}[1].EventHandler = function(ctl)"));
                    emitter.indent();
                    emitter.write_line(&format!("{handler_fn}(nil, ctl)"));
                    emitter.dedent();
                    emitter.write_line("end");
                    emitter.dedent();
                    emitter.write_line("end\n");
                } else {
                    let ch_1 = ch_idx + 1;
                    emitter.write_line(&format!("if {prop_ref} >= {ch_1} then"));
                    emitter.indent();
                    emitter.write_line(&format!("{ctl_ref}[{ch_1}].EventHandler = function(ctl)"));
                    emitter.indent();
                    emitter.write_line(&format!("{handler_fn}(nil, ctl)"));
                    emitter.dedent();
                    emitter.write_line("end");
                    emitter.dedent();
                    emitter.write_line("end\n");
                }
            } else {
                emitter.write_line(&format!("if {prop_ref} == 1 then"));
                emitter.indent();
                emitter.write_line(&format!("{ctl_ref}.EventHandler = function(c)"));
                emitter.indent();
                emitter.write_line(&format!("{handler_fn}(nil, c, 0)"));
                emitter.dedent();
                emitter.write_line("end");
                emitter.dedent();
                emitter.write_line("else");
                emitter.indent();
                emitter.write_line(&format!("for ix, ctl in ipairs({ctl_ref}) do"));
                emitter.indent();
                emitter.write_line("ctl.EventHandler = function(c)");
                emitter.indent();
                emitter.write_line(&format!("{handler_fn}(nil, c, ix - 1)"));
                emitter.dedent();
                emitter.write_line("end");
                emitter.dedent();
                emitter.write_line("end");
                emitter.dedent();
                emitter.write_line("end\n");
            }
        } else if let Some(ch_idx) = binding.channel_index {
            emitter.write_line(&format!(
                "{ctl_ref}[{}].EventHandler = function(ctl)",
                ch_idx + 1
            ));
            emitter.indent();
            emitter.write_line(&format!("{handler_fn}(nil, ctl)"));
            emitter.dedent();
            emitter.write_line("end\n");
        } else if ctl_count > 1 {
            emitter.write_line(&format!("for ix, ctl in ipairs({ctl_ref}) do"));
            emitter.indent();
            emitter.write_line("ctl.EventHandler = function(c)");
            emitter.indent();
            emitter.write_line(&format!("{handler_fn}(nil, c, ix - 1)"));
            emitter.dedent();
            emitter.write_line("end");
            emitter.dedent();
            emitter.write_line("end\n");
        } else {
            emitter.write_line(&format!("{ctl_ref}.EventHandler = function(ctl)"));
            emitter.indent();
            emitter.write_line(&format!("{handler_fn}(nil, ctl)"));
            emitter.dedent();
            emitter.write_line("end\n");
        }
    }

    // Emit plugin initialization statements
    if !plugin.init_body.is_empty() {
        emitter.write_line("-- Plugin initialization");
        emitter.emit_statements(&plugin.init_body);
    }

    // Invoke runtime(self) if implemented
    if plugin.methods.iter().any(|m| m.name == "runtime") {
        emitter.write_line(&format!("{}_runtime(nil)", plugin.class_name));
    }

    let mut runtime_helpers = String::new();
    if emitter.ctx.needs_ctl_index_helper {
        runtime_helpers.push_str(&format_ctl_index_helper());
    }
    if emitter.ctx.needs_generic_data_helper {
        runtime_helpers.push_str(&format_generic_data_helpers());
    }
    if !runtime_helpers.is_empty() {
        emitter.buffer.insert_str(runtime_body_offset, &runtime_helpers);
    }

    emitter.dedent();
    emitter.write_line("end");

    emitter.buffer
}

fn emit_plugin_info(emitter: &mut LuaEmitter<'_>, info: &qsys_model::PluginInfo) {
    emitter.write_line("PluginInfo = {");
    emitter.indent();
    emitter.write_line(&format!("Name = {},", escape_lua_string(&info.name)));
    emitter.write_line(&format!("Version = {},", escape_lua_string(&info.version)));
    emitter.write_line(&format!("Id = {},", escape_lua_string(&info.id)));
    emitter.write_line(&format!("Author = {},", escape_lua_string(&info.author)));
    if let Some(ref desc) = info.description {
        emitter.write_line(&format!("Description = {},", escape_lua_string(desc)));
    }
    if let Some(ref mfg) = info.manufacturer {
        emitter.write_line(&format!("Manufacturer = {},", escape_lua_string(mfg)));
    }
    emitter.write_line(&format!("ShowDebug = {},", info.show_debug));
    emitter.dedent();
    emitter.write_line("}\n");
}

fn emit_get_properties(emitter: &mut LuaEmitter<'_>, props: &[IRPropertyBinding]) {
    emitter.write_line("function GetProperties()");
    emitter.indent();
    emitter.write_line("local props = {}");

    for p in props {
        emitter.write_line("table.insert(props, {");
        emitter.indent();
        emitter.write_line(&format!("Name = {},", escape_lua_string(&p.def.name)));
        emitter.write_line(&format!(
            "Type = {},",
            escape_lua_string(p.def.kind.qsys_type_name())
        ));

        match &p.def.kind {
            PropertyKind::Integer { default, min, max } => {
                emitter.write_line(&format!("Value = {default},"));
                if let Some(m) = min {
                    emitter.write_line(&format!("Min = {m},"));
                }
                if let Some(m) = max {
                    emitter.write_line(&format!("Max = {m},"));
                }
            }
            PropertyKind::Double { default, min, max } => {
                emitter.write_line(&format!("Value = {},", format_lua_float(*default)));
                if let Some(m) = min {
                    emitter.write_line(&format!("Min = {},", format_lua_float(*m)));
                }
                if let Some(m) = max {
                    emitter.write_line(&format!("Max = {},", format_lua_float(*m)));
                }
            }
            PropertyKind::String { default } => {
                emitter.write_line(&format!("Value = {},", escape_lua_string(default)));
            }
            PropertyKind::Enum { choices, default } => {
                let choice_strs: Vec<_> = choices.iter().map(|c| escape_lua_string(c)).collect();
                emitter.write_line(&format!("Choices = {{ {} }},", choice_strs.join(", ")));
                emitter.write_line(&format!("Value = {},", escape_lua_string(default)));
            }
            PropertyKind::Boolean { default } => {
                emitter.write_line(&format!("Value = {default},"));
            }
        }

        if let Some(ref desc) = p.def.description {
            emitter.write_line(&format!("Description = {},", escape_lua_string(desc)));
        }

        emitter.dedent();
        emitter.write_line("})");
    }

    emitter.write_line("return props");
    emitter.dedent();
    emitter.write_line("end\n");
}

fn emit_control_table_insert(
    emitter: &mut LuaEmitter<'_>,
    c: &IRControlBinding,
    kind: &ControlKind,
) {
    emitter.write_line("table.insert(ctls, {");
    emitter.indent();
    emitter.write_line(&format!("Name = {},", escape_lua_string(&c.def.name)));
    emitter.write_line(&format!(
        "ControlType = {},",
        escape_lua_string(kind.qsys_type_str())
    ));

    match kind {
        ControlKind::Button { button_type } => {
            emitter.write_line(&format!(
                "ButtonType = {},",
                escape_lua_string(button_type.as_str())
            ));
        }
        ControlKind::Knob {
            unit,
            min,
            max,
            default,
        }
        | ControlKind::Fader {
            unit,
            min,
            max,
            default,
        } => {
            emitter.write_line(&format!(
                "ControlUnit = {},",
                escape_lua_string(unit.as_str())
            ));
            emitter.write_line(&format!("Min = {},", format_lua_float(*min)));
            emitter.write_line(&format!("Max = {},", format_lua_float(*max)));
            emitter.write_line(&format!("DefaultValue = {},", format_lua_float(*default)));
        }
        ControlKind::Text { text_type, default } => {
            emitter.write_line(&format!(
                "TextType = {},",
                escape_lua_string(text_type.as_str())
            ));
            emitter.write_line(&format!("String = {},", escape_lua_string(default)));
        }
        ControlKind::Indicator { unit } => {
            emitter.write_line(&format!(
                "ControlUnit = {},",
                escape_lua_string(unit.as_str())
            ));
        }
    }

    emitter.write_line(&format!(
        "PinStyle = {},",
        escape_lua_string(c.def.pin_style.as_str())
    ));
    emitter.write_line(&format!("UserPin = {},", c.def.user_pin));
    if let Some(ref prop_name) = c.def.count_property {
        emitter.write_line(&format!(
            "Count = {},",
            format_count_lua_expr(prop_name, "props")
        ));
    } else {
        emitter.write_line(&format!("Count = {},", c.def.count));
    }

    emitter.dedent();
    emitter.write_line("})");
}

fn emit_get_controls(emitter: &mut LuaEmitter<'_>, controls: &[IRControlBinding]) {
    emitter.write_line("function GetControls(props)");
    emitter.indent();
    emitter.write_line("local ctls = {}");

    for c in controls {
        if let Some(ref gspec) = c.def.generic_spec {
            let prop_expr = format!("props[{}].Value", escape_lua_string(&gspec.property_name));
            let choices: Vec<String> = if gspec.choices.is_empty() {
                vec![
                    "String".to_string(),
                    "Integer".to_string(),
                    "Float".to_string(),
                    "Boolean".to_string(),
                    "Trigger".to_string(),
                ]
            } else {
                gspec.choices.clone()
            };

            for (idx, choice) in choices.iter().enumerate() {
                let keyword = if idx == 0 { "if" } else { "elseif" };
                let kind = gspec.resolve_choice_kind(choice);
                emitter.write_line(&format!(
                    "{keyword} {prop_expr} == {} then",
                    escape_lua_string(choice)
                ));
                emitter.indent();
                emit_control_table_insert(emitter, c, &kind);
                emitter.dedent();
            }
            emitter.write_line("else");
            emitter.indent();
            emit_control_table_insert(emitter, c, &c.def.kind);
            emitter.dedent();
            emitter.write_line("end");
        } else {
            emit_control_table_insert(emitter, c, &c.def.kind);
        }
    }

    emitter.write_line("return ctls");
    emitter.dedent();
    emitter.write_line("end\n");
}

fn emit_get_pages(emitter: &mut LuaEmitter<'_>, pages: &[PageLayout]) {
    let page_names: Vec<String> = pages.iter().map(|p| escape_lua_string(&p.name)).collect();
    emitter.write_line(&format!(
        "local PageNames = {{ {} }}",
        page_names.join(", ")
    ));
    emitter.write_line("function GetPages(props)");
    emitter.indent();
    emitter.write_line("local pages = {}");
    emitter.write_line("for ix, name in ipairs(PageNames) do");
    emitter.indent();
    emitter.write_line("table.insert(pages, { name = name })");
    emitter.dedent();
    emitter.write_line("end");
    emitter.write_line("return pages");
    emitter.dedent();
    emitter.write_line("end\n");
}

fn emit_get_control_layout(emitter: &mut LuaEmitter<'_>, pages: &[PageLayout]) {
    emitter.write_line("function GetControlLayout(props)");
    emitter.indent();
    emitter.write_line("local layout = {}");
    emitter.write_line("local graphics = {}");

    if pages.len() == 1 {
        emit_page_layout_body(emitter, &pages[0]);
    } else if pages.len() > 1 {
        emitter.write_line("local CurrentPage = PageNames[props[\"page_index\"].Value]");
        for (idx, page) in pages.iter().enumerate() {
            let keyword = if idx == 0 { "if" } else { "elseif" };
            emitter.write_line(&format!(
                "{keyword} CurrentPage == {} then",
                escape_lua_string(&page.name)
            ));
            emitter.indent();
            emit_page_layout_body(emitter, page);
            emitter.dedent();
        }
        emitter.write_line("end");
    }

    emitter.write_line("return layout, graphics");
    emitter.dedent();
    emitter.write_line("end\n");
}

pub(crate) fn emit_page_layout_body(emitter: &mut LuaEmitter<'_>, page: &PageLayout) {
    for g in &page.graphics {
        if !g.skip_lua_emit {
            emit_graphic_item(emitter, g);
        }
    }
    for ctl in &page.controls {
        if !ctl.skip_lua_emit {
            emit_control_layout_item(emitter, ctl);
        }
    }
}

fn emit_graphic_item(emitter: &mut LuaEmitter<'_>, g: &GraphicItem) {
    let x = g.position.x.round() as i64;
    let y = g.position.y.round() as i64;
    let w = g.size.width.round() as i64;
    let h = g.size.height.round() as i64;

    emitter.write_line("table.insert(graphics, {");
    emitter.indent();
    match &g.kind {
        GraphicItemKind::Header { text, font_size } => {
            emitter.write_line("Type = \"Header\",");
            emitter.write_line(&format!("Text = {},", escape_lua_string(text)));
            emitter.write_line(&format!("Position = {{ {x}, {y} }},"));
            emitter.write_line(&format!("Size = {{ {w}, {h} }},"));
            emitter.write_line(&format!("FontSize = {font_size},"));
            emitter.write_line("HTextAlign = \"Left\",");
            if let Some(ref color) = g.color {
                let (r, gr, b) = color.to_rgb_tuple();
                emitter.write_line(&format!("Color = {{ {r}, {gr}, {b} }},"));
            }
        }
        GraphicItemKind::GroupBox { text, stroke } => {
            emitter.write_line("Type = \"GroupBox\",");
            emitter.write_line(&format!("Text = {},", escape_lua_string(text)));
            emitter.write_line(&format!("Position = {{ {x}, {y} }},"));
            emitter.write_line(&format!("Size = {{ {w}, {h} }},"));
            emitter.write_line(&format!("StrokeWidth = {stroke},"));
            emitter.write_line("CornerRadius = 4,");
            emitter.write_line("HTextAlign = \"Left\",");
            if let Some(ref fill) = g.color {
                let (r, gr, b) = fill.to_rgb_tuple();
                emitter.write_line(&format!("Fill = {{ {r}, {gr}, {b} }},"));
            }
        }
        GraphicItemKind::Label {
            text,
            font_size,
            h_align,
        } => {
            emitter.write_line("Type = \"Label\",");
            emitter.write_line(&format!("Text = {},", escape_lua_string(text)));
            emitter.write_line(&format!("Position = {{ {x}, {y} }},"));
            emitter.write_line(&format!("Size = {{ {w}, {h} }},"));
            emitter.write_line(&format!("FontSize = {font_size},"));
            emitter.write_line(&format!("HTextAlign = {},", escape_lua_string(h_align)));
            if let Some(ref color) = g.color {
                let (r, gr, b) = color.to_rgb_tuple();
                emitter.write_line(&format!("Color = {{ {r}, {gr}, {b} }},"));
            }
        }
        GraphicItemKind::Separator => {
            emitter.write_line("Type = \"Header\",");
            emitter.write_line("Text = \"\",");
            emitter.write_line(&format!("Position = {{ {x}, {y} }},"));
            emitter.write_line(&format!("Size = {{ {w}, {h} }},"));
        }
    }
    emitter.dedent();
    emitter.write_line("})");
}

fn format_dynamic_channel_lua_expr(template: &str, prop_expr: &str) -> String {
    let normalized = template.replace("{ch}", "{i}");
    if let Some((prefix, suffix)) = normalized.split_once("{i}") {
        let mut parts = Vec::new();
        if !prefix.is_empty() {
            parts.push(escape_lua_string(prefix));
        }
        parts.push("tostring(i)".to_string());
        if !suffix.is_empty() {
            parts.push(escape_lua_string(suffix));
        }
        parts.join(" .. ")
    } else {
        let single = escape_lua_string(template);
        let multi_prefix = escape_lua_string(&format!("{template} "));
        format!("({prop_expr} == 1) and {single} or ({multi_prefix} .. tostring(i))")
    }
}

fn build_dynamic_style_lua_expr(emitter: &LuaEmitter<'_>, type_prop: &str) -> String {
    let prop_expr = format!("props[{}].Value", escape_lua_string(type_prop));
    let matching_gspec = emitter.ctx.controls.values().find_map(|d| {
        d.generic_spec
            .as_ref()
            .filter(|g| g.property_name == type_prop && !g.choices.is_empty())
    });

    if let Some(gspec) = matching_gspec {
        if gspec.choices.len() == 1 {
            let st = ControlStyle::default_for_kind(&gspec.resolve_choice_kind(&gspec.choices[0]));
            return escape_lua_string(st.as_str());
        }
        let mut expr = {
            let last_choice = gspec.choices.last().unwrap();
            let st = ControlStyle::default_for_kind(&gspec.resolve_choice_kind(last_choice));
            escape_lua_string(st.as_str())
        };
        for choice in gspec.choices[..gspec.choices.len() - 1].iter().rev() {
            let st = ControlStyle::default_for_kind(&gspec.resolve_choice_kind(choice));
            let st_str = escape_lua_string(st.as_str());
            let choice_str = escape_lua_string(choice);
            expr = format!("({prop_expr} == {choice_str}) and {st_str} or ({expr})");
        }
        return expr;
    }

    format!(
        "({prop_expr} == \"String\" or {prop_expr} == \"Text\") and \"Text\" or (({prop_expr} == \"Boolean\" or {prop_expr} == \"Toggle\" or {prop_expr} == \"Button\" or {prop_expr} == \"Trigger\") and \"Button\" or \"Knob\")"
    )
}

fn emit_control_layout_fields(
    emitter: &mut LuaEmitter<'_>,
    ctl: &ControlLayoutDef,
    pretty_expr: &str,
    pos_x_expr: &str,
    pos_y_expr: &str,
    w: i64,
    h: i64,
) {
    emitter.write_line(&format!("PrettyName = {pretty_expr},"));
    if let Some(ref type_prop) = ctl.type_property {
        let style_expr = build_dynamic_style_lua_expr(emitter, type_prop);
        emitter.write_line(&format!("Style = {style_expr},"));
    } else if let Some(ref style) = ctl.style {
        emitter.write_line(&format!("Style = {},", escape_lua_string(style.as_str())));
    }
    emitter.write_line(&format!("Position = {{ {pos_x_expr}, {pos_y_expr} }},"));
    emitter.write_line(&format!("Size = {{ {w}, {h} }},"));
    if let Some(ref color) = ctl.color {
        let (r, g, b) = color.to_rgb_tuple();
        emitter.write_line(&format!("Color = {{ {r}, {g}, {b} }},"));
    }
    if let Some(ref legend) = ctl.legend {
        emitter.write_line(&format!("Legend = {},", escape_lua_string(legend)));
    }
    if let Some(margin) = ctl.margin {
        emitter.write_line(&format!("Margin = {},", margin.round() as i64));
    }
    if ctl.is_disabled {
        emitter.write_line("IsReadOnly = true,");
    }
}

fn emit_control_layout_item(emitter: &mut LuaEmitter<'_>, ctl: &ControlLayoutDef) {
    let x = ctl.position.x.round() as i64;
    let y = ctl.position.y.round() as i64;
    let w = ctl.size.width.round() as i64;
    let h = ctl.size.height.round() as i64;

    if let Some(ref rep) = ctl.dynamic_repeat {
        let prop_expr = format_count_lua_expr(&rep.count_property, "props");
        let base_str = escape_lua_string(&rep.base_control_name);
        let base_prefix = escape_lua_string(&format!("{} ", rep.base_control_name));
        let dx = rep.step_x.round() as i64;
        let dy = rep.step_y.round() as i64;

        emitter.write_line(&format!("for i = 1, {prop_expr} do"));
        emitter.indent();

        if let Some(ref lbl_tmpl) = rep.label_template {
            let lx = (ctl.position.x + rep.label_offset_x).round() as i64;
            let ly = (ctl.position.y + rep.label_offset_y).round() as i64;
            let lw = rep.label_width.round() as i64;
            let lh = rep.label_height.round() as i64;
            let l_pos_x = if dx == 0 {
                lx.to_string()
            } else {
                format!("{lx} + (i - 1) * {dx}")
            };
            let l_pos_y = if dy == 0 {
                ly.to_string()
            } else {
                format!("{ly} + (i - 1) * {dy}")
            };
            let lbl_text_expr = format_dynamic_channel_lua_expr(lbl_tmpl, &prop_expr);

            emitter.write_line("table.insert(graphics, {");
            emitter.indent();
            emitter.write_line("Type = \"Label\",");
            emitter.write_line(&format!("Text = {lbl_text_expr},"));
            emitter.write_line(&format!("Position = {{ {l_pos_x}, {l_pos_y} }},"));
            emitter.write_line(&format!("Size = {{ {lw}, {lh} }},"));
            emitter.write_line(&format!("FontSize = {},", rep.label_font_size));
            emitter.write_line("HTextAlign = \"Left\",");
            emitter.dedent();
            emitter.write_line("})");
        }

        let pos_x = if dx == 0 {
            x.to_string()
        } else {
            format!("{x} + (i - 1) * {dx}")
        };
        let pos_y = if dy == 0 {
            y.to_string()
        } else {
            format!("{y} + (i - 1) * {dy}")
        };
        let pretty_expr = format_dynamic_channel_lua_expr(&rep.pretty_name_template, &prop_expr);

        emitter.write_line(&format!(
            "local ctl_key = ({prop_expr} == 1) and {base_str} or ({base_prefix} .. tostring(i))"
        ));
        emitter.write_line("layout[ctl_key] = {");
        emitter.indent();
        emit_control_layout_fields(emitter, ctl, &pretty_expr, &pos_x, &pos_y, w, h);
        emitter.dedent();
        emitter.write_line("}");

        emitter.dedent();
        emitter.write_line("end");
        return;
    }

    let pretty = escape_lua_string(ctl.pretty_name.as_deref().unwrap_or(&ctl.name));
    let x_str = x.to_string();
    let y_str = y.to_string();

    if let (Some(prop_name), Some(base_name), Some(ch)) = (
        &ctl.count_property,
        &ctl.base_control_name,
        ctl.channel_index,
    ) {
        let prop_expr = format_count_lua_expr(prop_name, "props");
        if ch == 1 {
            let key_expr = format!(
                "({prop_expr} == 1) and {} or {}",
                escape_lua_string(base_name),
                escape_lua_string(&ctl.name)
            );
            emitter.write_line(&format!("layout[{key_expr}] = {{"));
            emitter.indent();
            emit_control_layout_fields(emitter, ctl, &pretty, &x_str, &y_str, w, h);
            emitter.dedent();
            emitter.write_line("}");
        } else {
            emitter.write_line(&format!("if {prop_expr} >= {ch} then"));
            emitter.indent();
            emitter.write_line(&format!("layout[{}] = {{", escape_lua_string(&ctl.name)));
            emitter.indent();
            emit_control_layout_fields(emitter, ctl, &pretty, &x_str, &y_str, w, h);
            emitter.dedent();
            emitter.write_line("}");
            emitter.dedent();
            emitter.write_line("end");
        }
        return;
    }

    emitter.write_line(&format!("layout[{}] = {{", escape_lua_string(&ctl.name)));
    emitter.indent();
    emit_control_layout_fields(emitter, ctl, &pretty, &x_str, &y_str, w, h);
    emitter.dedent();
    emitter.write_line("}");
}

fn emit_lifecycle_method(emitter: &mut LuaEmitter<'_>, lua_fn_name: &str, method: &IRFunction) {
    let mut param_names = Vec::new();
    for param in &method.params {
        emitter
            .ctx
            .symbol_names
            .insert(param.id, param.name.clone());
        emitter.ctx.declared_locals.insert(param.id);
        param_names.push(param.name.clone());
    }

    emitter.write_line(&format!(
        "function {}({})",
        lua_fn_name,
        param_names.join(", ")
    ));
    emitter.indent();
    emitter.emit_statements(&method.body);
    emitter.dedent();
    emitter.write_line("end\n");
}

fn emit_method(emitter: &mut LuaEmitter<'_>, class_name: &str, method: &IRFunction) {
    let fn_name = format!("{class_name}_{}", method.name);
    let mut param_names = Vec::new();

    let prev_handler_ctl = emitter.ctx.active_handler_control;
    let handler_ctl = emitter
        .ctx
        .method_handler_controls
        .get(&method.name)
        .copied();
    emitter.ctx.active_handler_control = handler_ctl;
    if let (Some(ctl_id), Some(first_param)) = (handler_ctl, method.params.first()) {
        emitter.ctx.local_controls.insert(first_param.id, ctl_id);
    }

    // The first parameter is `self`
    param_names.push("self".to_string());

    for param in &method.params {
        emitter
            .ctx
            .symbol_names
            .insert(param.id, param.name.clone());
        emitter.ctx.declared_locals.insert(param.id);
        param_names.push(param.name.clone());
    }

    emitter.write_line(&format!(
        "local function {fn_name}({})",
        param_names.join(", ")
    ));
    emitter.indent();
    emitter.emit_statements(&method.body);
    emitter.dedent();
    emitter.write_line("end\n");

    emitter.ctx.active_handler_control = prev_handler_ctl;
}

fn format_ctl_index_helper() -> String {
    let mut out = String::new();
    out.push_str("    local function __qsys_ctl(ctl, idx, count)\n");
    out.push_str("        if count == 1 or type(ctl) ~= \"table\" then return ctl end\n");
    out.push_str("        return ctl[idx]\n");
    out.push_str("    end\n\n");
    out
}

fn format_generic_data_helpers() -> String {
    let mut out = String::new();
    out.push_str("    local function __qsys_get_data(ctl, kind)\n");
    out.push_str("        local k = kind and string.lower(tostring(kind)) or \"\"\n");
    out.push_str(
        "        if k == \"string\" or k == \"text\" or k == \"readonly\" or k == \"pin\" then\n",
    );
    out.push_str("            return ctl.String\n");
    out.push_str("        elseif k == \"boolean\" or k == \"bool\" or k == \"toggle\" or k == \"button\" or k == \"momentary\" or k == \"trigger\" or k == \"indicator\" or k == \"led\" then\n");
    out.push_str("            return ctl.Boolean\n");
    out.push_str("        else\n");
    out.push_str("            return ctl.Value\n");
    out.push_str("        end\n");
    out.push_str("    end\n\n");
    out.push_str("    local function __qsys_set_data(ctl, val, kind)\n");
    out.push_str("        local k = kind and string.lower(tostring(kind)) or \"\"\n");
    out.push_str(
        "        if k == \"string\" or k == \"text\" or k == \"readonly\" or k == \"pin\" then\n",
    );
    out.push_str("            ctl.String = tostring(val)\n");
    out.push_str("        elseif k == \"boolean\" or k == \"bool\" or k == \"toggle\" or k == \"button\" or k == \"momentary\" or k == \"trigger\" or k == \"indicator\" or k == \"led\" then\n");
    out.push_str("            ctl.Boolean = not not val\n");
    out.push_str("        else\n");
    out.push_str("            ctl.Value = tonumber(val) or 0\n");
    out.push_str("        end\n");
    out.push_str("    end\n\n");
    out
}

fn emit_truthy_helper(emitter: &mut LuaEmitter<'_>) {
    emitter.write_line("local function __py_truthy(v)");
    emitter.indent();
    emitter.write_line("if v == nil or v == false then return false end");
    emitter.write_line("if type(v) == \"number\" then return v ~= 0 end");
    emitter.write_line("if type(v) == \"string\" then return #v > 0 end");
    emitter.write_line("if type(v) == \"table\" then return next(v) ~= nil end");
    emitter.write_line("return true");
    emitter.dedent();
    emitter.write_line("end\n");
}
