use qsys_ir::*;

use crate::context::CodegenContext;
use crate::emitter::{LuaEmitter, escape_lua_string};

pub fn emit_script(script: &IRScript, ctx: &mut CodegenContext) -> String {
    for ctl in &script.controls {
        ctx.controls.insert(ctl.id, ctl.def.clone());
    }
    ctx.symbol_names.extend(script.symbol_names.clone());
    for func in &script.methods {
        ctx.functions.insert(func.id, func.name.clone());
    }

    let mut emitter = LuaEmitter::new(ctx);

    emitter.write_line("-- Generated by QSysPy Compiler (Lua 5.3)");
    if script.is_controller {
        emitter.write_line("-- Target: Q-SYS Text Controller / Script Component\n");
    } else {
        emitter.write_line("-- Target: Q-SYS Procedural Script\n");
    }

    if !script.is_controller {
        let mut combined = Vec::with_capacity(script.body.len() + script.methods.len());
        combined.extend(script.body.iter().cloned());
        combined.extend(script.methods.iter().cloned().map(IRStmt::FunctionDef));
        emitter.emit_hoisted_statements(&combined);
        return emitter.buffer;
    }

    // Emit module-level statements (imports, helper classes, helper functions) before controller methods
    if !script.top_level_stmts.is_empty() {
        emitter.emit_hoisted_statements(&script.top_level_stmts);
    }

    // Emit functions
    for func in &script.methods {
        let mut param_names = Vec::new();
        for param in &func.params {
            emitter
                .ctx
                .symbol_names
                .insert(param.id, param.name.clone());
            emitter.ctx.declared_locals.insert(param.id);
            param_names.push(param.name.clone());
        }

        emitter.write_line(&format!(
            "local function {}({})",
            func.name,
            param_names.join(", ")
        ));
        emitter.indent();
        emitter.emit_param_defaults(&func.params);
        emitter.emit_statements(&func.body);
        emitter.dedent();
        emitter.write_line("end\n");
    }

    // Emit event bindings
    for binding in &script.event_bindings {
        let ctl_ref = format!("Controls[{}]", escape_lua_string(&binding.control_name));
        let ctl_count = script
            .controls
            .iter()
            .find(|c| c.id == binding.control_id)
            .map(|c| c.def.count)
            .unwrap_or(1);

        if let Some(ch_idx) = binding.channel_index {
            emitter.write_line(&format!(
                "{ctl_ref}[{}].EventHandler = function(ctl)",
                ch_idx + 1
            ));
            emitter.indent();
            emitter.write_line(&format!("{}(ctl)", binding.handler_name));
            emitter.dedent();
            emitter.write_line("end\n");
        } else if ctl_count > 1 {
            emitter.write_line(&format!("for ix, ctl in ipairs({ctl_ref}) do"));
            emitter.indent();
            emitter.write_line("ctl.EventHandler = function(c)");
            emitter.indent();
            emitter.write_line(&format!("{}(c, ix - 1)", binding.handler_name));
            emitter.dedent();
            emitter.write_line("end");
            emitter.dedent();
            emitter.write_line("end\n");
        } else {
            emitter.write_line(&format!("{ctl_ref}.EventHandler = function(ctl)"));
            emitter.indent();
            emitter.write_line(&format!("{}(ctl)", binding.handler_name));
            emitter.dedent();
            emitter.write_line("end\n");
        }
    }

    // Emit top-level body statements with declaration hoisting (classes before functions before executable statements)
    emitter.emit_hoisted_statements(&script.body);

    emitter.buffer
}
